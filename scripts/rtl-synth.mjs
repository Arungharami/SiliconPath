// Generates or verifies rtl-synth.js: real Yosys output shown in the RTL
// track's synthesis module. Called by scripts/rtl-crosscheck.mjs.
//
// --write-synth: run Yosys and write rtl-synth.js.
// --verify-synth: check the committed file. The netlist must simulate in
// Icarus to the same outputs the engine computes for the reference design,
// and the recorded cell counts must match the netlist text. If the installed
// Yosys has the same version string, the output must also be byte-identical.
import { readFile, writeFile } from "node:fs/promises";
import { execFileSync, spawnSync } from "node:child_process";
import { join } from "node:path";
import vm from "node:vm";

const target = new URL("../rtl-synth.js", import.meta.url);
const yosysVersion = () =>
  execFileSync("yosys", ["-V"], { encoding: "utf8" }).trim();

function runYosys(dir, src, top, script) {
  const file = join(dir, "synth_in.v");
  const net = join(dir, "synth_net.v");
  const stat = join(dir, "synth_stat.json");
  return writeFile(file, src).then(async () => {
    execFileSync(
      "yosys",
      [
        "-q",
        "-p",
        `read_verilog ${file}; ${script}; tee -q -o ${stat} stat -json -tech cmos; write_verilog -noattr ${net}`,
      ],
      { stdio: "pipe" },
    );
    const json = JSON.parse(await readFile(stat, "utf8"));
    const mod = json.modules[`\\${top}`] || Object.values(json.modules)[0];
    const cells = Object.fromEntries(
      Object.entries(mod.num_cells_by_type).filter(([k]) => k.startsWith("$_")),
    );
    return {
      netlist: (await readFile(net, "utf8")).trim(),
      stat: {
        cells,
        transistors: String(mod.estimated_num_transistors),
      },
    };
  });
}

function latchLog(dir, src, top) {
  const file = join(dir, "design.v");
  return writeFile(file, src).then(() => {
    const r = spawnSync(
      "yosys",
      ["-q", "-p", `read_verilog ${file}; hierarchy -top ${top}; proc`],
      { encoding: "utf8" },
    );
    return ((r.stdout || "") + (r.stderr || ""))
      .split("\n")
      .filter((l) => /Latch inferred/.test(l))
      .map((l) => l.split(file).join("design.v").trim())
      .join("\n");
  });
}

const render = (data) =>
  `// Generated by: node scripts/rtl-crosscheck.mjs --write-synth\n// Real Yosys output for the RTL track's reference designs. Do not edit by hand.\nwindow.RtlSynth = ${JSON.stringify(data, null, 2)};\n`;

async function generate(ctx, dir) {
  const T = ctx.RtlTrack;
  const data = {
    yosys: yosysVersion(),
    generated: new Date().toISOString().slice(0, 10),
    designs: {},
    latchLogs: {},
  };
  for (const d of T.synthDesigns())
    data.designs[d.id] = {
      script: d.script,
      ...(await runYosys(dir, d.src, d.top, d.script)),
    };
  for (const d of T.latchDesigns())
    data.latchLogs[d.id] = await latchLog(dir, d.src, d.top);
  return data;
}

function loadCommitted(text) {
  const c = vm.createContext({ window: {} });
  vm.runInContext(text, c);
  return c.window.RtlSynth;
}

export async function synthesize(ctx, dir, write) {
  const fresh = await generate(ctx, dir);
  if (write) {
    await writeFile(target, render(fresh));
    return { ok: true, message: `wrote rtl-synth.js with ${fresh.yosys}` };
  }
  let committed;
  try {
    committed = loadCommitted(await readFile(target, "utf8"));
  } catch (e) {
    return {
      ok: false,
      message: "rtl-synth.js missing or invalid: " + e.message,
    };
  }
  const T = ctx.RtlTrack,
    E = ctx.RtlEngine;
  for (const d of T.synthDesigns()) {
    const c = committed.designs?.[d.id];
    if (!c) return { ok: false, message: `no committed netlist for ${d.id}` };
    // 1. Recorded counts agree with the netlist text and Yosys's stat.
    const counts = T.netlistCounts(c.netlist);
    const want = {
      $_NAND_: counts.nand,
      $_NOR_: counts.nor,
      $_NOT_: counts.not,
    };
    for (const [k, v] of Object.entries(want))
      if ((c.stat.cells[k] || 0) !== v)
        return {
          ok: false,
          message: `${d.id}: ${k} count ${c.stat.cells[k]} in stat but ${v} in netlist text`,
        };
    if (
      Object.keys(c.stat.cells).some((k) => !(k in want)) ||
      !c.stat.transistors.startsWith(String(counts.transistors))
    )
      return {
        ok: false,
        message: `${d.id}: unexpected cell types or transistor estimate ${c.stat.transistors}`,
      };
    // 2. The committed netlist is functionally the reference design.
    const refDesign = E.compile(d.src, d.top);
    const tb = E.testbench({
      top: d.top,
      inputs: E.ports(refDesign, "input"),
      outputs: E.ports(refDesign, "output"),
      rows: E.exhaustive(refDesign),
      vcd: false,
    });
    await writeFile(join(dir, "net.v"), c.netlist);
    await writeFile(join(dir, "net_tb.v"), tb);
    execFileSync(
      "iverilog",
      [
        "-g2005",
        "-o",
        join(dir, "net_sim"),
        join(dir, "net.v"),
        join(dir, "net_tb.v"),
      ],
      { stdio: "pipe" },
    );
    const out = execFileSync("vvp", ["-n", join(dir, "net_sim")], {
      encoding: "utf8",
    });
    if (!out.includes("PASS"))
      return {
        ok: false,
        message: `${d.id}: committed netlist does not match the reference:\n${out}`,
      };
  }
  // 3. Same Yosys version: output must be identical.
  if (committed.yosys === fresh.yosys) {
    const strip = (x) => JSON.stringify({ ...x, generated: "" });
    if (strip(committed) !== strip(fresh))
      return {
        ok: false,
        message:
          "rtl-synth.js differs from a fresh run with the same Yosys version; rerun with --write-synth",
      };
    return {
      ok: true,
      message: `committed netlist verified and identical to a fresh ${fresh.yosys} run`,
    };
  }
  return {
    ok: true,
    message: `committed netlist (${committed.yosys}) verified functionally with Icarus; installed ${fresh.yosys} differs, so byte comparison was skipped`,
  };
}
